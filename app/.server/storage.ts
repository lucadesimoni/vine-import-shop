import { mkdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, normalize } from "node:path";
import { randomBytes } from "node:crypto";

/**
 * Uploads and generated images, three drivers:
 *   local     ./data/uploads, served by /uploads/* (one server, Docker volume)
 *   s3        any S3-compatible bucket: AWS, Cloudflare R2, Exoscale SOS, Infomaniak … (S3_* variables)
 *   supabase  Supabase Storage (e.g. region Zurich). Chosen automatically when SUPABASE_URL and a service key are
 *             set (the Vercel ↔ Supabase integration sets both). The public bucket SUPABASE_BUCKET (default "media")
 *             is created on first use.
 */
export type StorageDriver = "local" | "s3" | "supabase";
const supabaseKey = () => process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SECRET_KEY || "";
export function storageDriver(): StorageDriver {
  const d = process.env.STORAGE_DRIVER;
  if (d === "s3" || d === "supabase" || d === "local") return d;
  return process.env.SUPABASE_URL && supabaseKey() ? "supabase" : "local";
}
/** origins of the configured object storage — their images may be resized by /media/img */
export function mediaOrigins(): string[] {
  const out: string[] = [];
  for (const u of [process.env.S3_PUBLIC_URL, process.env.SUPABASE_URL]) { try { if (u) out.push(new URL(u).origin); } catch { /* ignore */ } }
  return out;
}

/** files survive restarts and are shared by all instances (serverless needs this) */
export const persistentStorage = () => storageDriver() !== "local" || !process.env.VERCEL;
// Serverless filesystems are read-only except /tmp → use STORAGE_DRIVER=s3 for persistent uploads there.
const LOCAL_DIR = process.env.UPLOAD_DIR ?? (process.env.VERCEL ? "/tmp/uploads" : join(process.cwd(), "data/uploads"));
const TYPES: Record<string, string> = { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".avif": "image/avif", ".svg": "image/svg+xml", ".gif": "image/gif" };
const MAX = 8 * 1024 * 1024;

/**
 * SVG (logos) is accepted only with { svg: true }, only for local storage (served with a CSP sandbox, see
 * routes/resources/uploads.ts) and only without scripts, event handlers, foreign objects or external references.
 */
export async function saveUpload(file: File, folder = "media", opts: { svg?: boolean } = {}): Promise<string> {
  const ext = extname(file.name).toLowerCase();
  if (!TYPES[ext]) throw new Error("Unsupported file type");
  if (ext === ".svg" && (!opts.svg || storageDriver() !== "local")) throw new Error("SVG is not supported here — please upload PNG or WebP");
  if (file.size > MAX) throw new Error("File too large (max 8 MB)");
  const key = `${folder}/${Date.now().toString(36)}-${randomBytes(4).toString("hex")}${ext}`;
  const body = new Uint8Array(await file.arrayBuffer());
  if (ext === ".svg" && !isSafeSvg(new TextDecoder().decode(body))) throw new Error("SVG contains scripts or external references");

  return put(key, body, TYPES[ext], "public, max-age=31536000, immutable");
}

/** Store generated bytes under a fixed key (e.g. optimized images) — same drivers as saveUpload. */
export function saveBuffer(key: string, body: Uint8Array, type: string): Promise<string> {
  return put(key, body, type, "public, max-age=31536000, immutable");
}

/** write one object with the active driver → its public URL */
async function put(key: string, body: Uint8Array, type: string, cache: string): Promise<string> {
  const driver = storageDriver();
  if (driver === "s3") {
    const { AwsClient } = await import("aws4fetch");
    const aws = new AwsClient({ accessKeyId: process.env.S3_ACCESS_KEY_ID!, secretAccessKey: process.env.S3_SECRET_ACCESS_KEY!, region: process.env.S3_REGION ?? "auto", service: "s3" });
    const res = await aws.fetch(`${process.env.S3_ENDPOINT}/${process.env.S3_BUCKET}/${key}`, { method: "PUT", body: body as unknown as BodyInit, headers: { "Content-Type": type, "Cache-Control": cache } });
    if (!res.ok) throw new Error(`Upload failed: ${res.status}`);
    return `${process.env.S3_PUBLIC_URL?.replace(/\/$/, "")}/${key}`;
  }
  if (driver === "supabase") return supabasePut(key, body, type, cache);
  const path = join(LOCAL_DIR, key);
  await mkdir(join(path, ".."), { recursive: true });
  await writeFile(path, body);
  return `/uploads/${key}`;
}

/* ── Supabase Storage (REST API with the service key; never sent to the browser) ── */
let bucketReady: Promise<void> | undefined;
function supabaseHeaders(extra: Record<string, string> = {}) {
  const key = supabaseKey();
  // legacy service_role keys are JWTs (Bearer); new secret keys (sb_secret_…) go in the apikey header only
  return { apikey: key, ...(key.startsWith("eyJ") ? { Authorization: `Bearer ${key}` } : {}), ...extra };
}
async function supabasePut(key: string, body: Uint8Array, type: string, cache: string): Promise<string> {
  const base = process.env.SUPABASE_URL!.replace(/\/$/, "");
  const bucket = process.env.SUPABASE_BUCKET || "media";
  bucketReady ??= fetch(`${base}/storage/v1/bucket`, {
    method: "POST",
    headers: supabaseHeaders({ "Content-Type": "application/json" }),
    body: JSON.stringify({ id: bucket, name: bucket, public: true, file_size_limit: MAX * 2, allowed_mime_types: Object.values(TYPES) }),
  }).then(async (r) => {
    // 409/400 "already exists" is fine
    if (!r.ok && !/exist/i.test(await r.text())) throw new Error(`Supabase bucket: HTTP ${r.status}`);
  });
  await bucketReady.catch((e) => { bucketReady = undefined; throw e; });
  const res = await fetch(`${base}/storage/v1/object/${bucket}/${key}`, {
    method: "POST",
    headers: supabaseHeaders({ "Content-Type": type, "Cache-Control": cache.replace(/^public, max-age=(\d+).*/, "max-age=$1"), "x-upsert": "true" }),
    body: body as unknown as BodyInit,
  });
  if (!res.ok) throw new Error(`Upload failed: HTTP ${res.status} ${(await res.text()).slice(0, 120)}`);
  return `${base}/storage/v1/object/public/${bucket}/${key}`;
}

export async function readUpload(key: string): Promise<{ body: Uint8Array; type: string } | null> {
  const safe = normalize(key).replace(/^(\.\.(\/|\\|$))+/, "");
  if (safe.includes("..")) return null;
  try {
    const body = await readFile(join(LOCAL_DIR, safe));
    return { body: new Uint8Array(body), type: TYPES[extname(safe).toLowerCase()] ?? "application/octet-stream" };
  } catch {
    return null;
  }
}

export function isSafeSvg(text: string) {
  if (!/<svg[\s>]/i.test(text)) return false;
  return !/<script|<foreignObject|<iframe|<embed|<object|\son\w+\s*=|javascript:|data:text\/html|<!ENTITY|xlink:href\s*=\s*["']\s*(https?:|\/\/)|href\s*=\s*["']\s*(https?:|\/\/)/i.test(text);
}
