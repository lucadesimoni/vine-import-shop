#!/usr/bin/env node
// Third-party licence inventory of everything shipped at runtime (dependencies, transitively).
//   npm run licenses          → writes THIRD_PARTY_LICENSES.md
//   npm run licenses:check    → fails if a dependency has a copyleft or unknown licence (CI)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = process.cwd();
const ALLOWED = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|0BSD|Apache-2\.0|BlueOak-1\.0\.0|CC0-1\.0|CC-BY-4\.0|Unlicense|Python-2\.0|MPL-2\.0|WTFPL|MIT-0)$/;
const check = process.argv.includes("--check");

const pkgJson = (dir) => JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
function resolve(name, from) {
  for (let d = from; ; d = dirname(d)) {
    const p = join(d, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return p;
    if (d === dirname(d)) return null;
  }
}
const licenceOf = (p) => {
  const l = p.license ?? p.licenses;
  if (typeof l === "string") return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(" OR ");
  return l?.type ?? "UNKNOWN";
};

const seen = new Map();
const queue = Object.keys(pkgJson(root).dependencies ?? {}).map((n) => [n, root]);
while (queue.length) {
  const [name, from] = queue.shift();
  const dir = resolve(name, from);
  if (!dir) continue;
  const p = pkgJson(dir);
  const key = `${p.name}@${p.version}`;
  if (seen.has(key)) continue;
  seen.set(key, { name: p.name, version: p.version, license: licenceOf(p), repo: typeof p.repository === "string" ? p.repository : p.repository?.url ?? p.homepage ?? "" });
  for (const dep of Object.keys({ ...(p.dependencies ?? {}), ...(p.optionalDependencies ?? {}) })) queue.push([dep, dir]);
}

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const ok = (l) => l.split(/\s+OR\s+|\s+AND\s+|[()]/).map((x) => x.trim()).filter(Boolean).some((x) => ALLOWED.test(x));
const bad = rows.filter((r) => !ok(r.license));
if (check) {
  if (bad.length) { console.error(`✗ ${bad.length} dependencies with copyleft/unknown licences:\n` + bad.map((r) => `  ${r.name}@${r.version}: ${r.license}`).join("\n")); process.exit(1); }
  console.log(`✓ ${rows.length} runtime dependencies, all permissive`);
  process.exit(0);
}
const byLicence = rows.reduce((m, r) => m.set(r.license, (m.get(r.license) ?? 0) + 1), new Map());
writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), [
  "# Third-party licences",
  "",
  "Open-source packages shipped with the platform at runtime (generated by `npm run licenses`; development tools are not distributed and not listed).",
  "Each package remains under its own licence; the full licence texts are included in the respective package in `node_modules`.",
  "",
  `**${rows.length} packages** · ` + [...byLicence].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(" · "),
  "",
  "| Package | Version | Licence |",
  "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
].join("\n"));
console.log(`✓ THIRD_PARTY_LICENSES.md — ${rows.length} packages${bad.length ? `, ${bad.length} need review` : ""}`);
